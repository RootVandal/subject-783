let lang = 'ru';
try {
  const saved = localStorage.getItem('s783-lang');
  lang = saved || ((navigator.language || 'ru').toLowerCase().startsWith('ru') ? 'ru' : 'en');
} catch { /* storage blocked */ }

const listeners = new Set();
export const t = (k) => STR[lang][k] ?? STR.en[k] ?? k;
export const getLang = () => lang;
export function setLang(l) {
  lang = l;
  try { localStorage.setItem('s783-lang', l); } catch { /* ignore */ }
  apply();
  listeners.forEach((f) => f(l));
}
export const onLang = (f) => listeners.add(f);
export function apply(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-lang-block]').forEach((el) => { el.hidden = el.dataset.langBlock !== lang; });
  root.querySelectorAll('[data-lang]').forEach((el) => el.classList.toggle('on', el.dataset.lang === lang));
}
